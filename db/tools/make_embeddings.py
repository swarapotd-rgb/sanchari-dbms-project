#!/usr/bin/env python3
r"""
Sanchari - writes db/06e_seed_embeddings.sql from db/data/places.csv.

Each place's short_description is turned into 384 numbers by the
all-MiniLM-L6-v2 sentence-transformer. Places whose descriptions MEAN
similar things get vectors that point in similar directions, which is
what the <=> (cosine distance) search in pgvector compares.

Run it from the repo root, after places.csv is final:

    pip install sentence-transformers        (once; also installs PyTorch)
    python db/tools/make_embeddings.py

The first run downloads the model (about 90 MB). The first time, also
add this line at the end of db/run_all.sql:

    \ir 06e_seed_embeddings.sql

then rebuild the database.

Re-run this whenever you add places or change a description.
"""

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CSV_IN = ROOT / "db" / "data" / "places.csv"
SQL_OUT = ROOT / "db" / "06e_seed_embeddings.sql"
MODEL = "all-MiniLM-L6-v2"


def sql_text(s):
    """Quote a value as an SQL string literal."""
    return "'" + s.replace("'", "''") + "'"


def main(encode=None):
    with open(CSV_IN, encoding="utf-8-sig", newline="") as f:
        rows = [r for r in csv.DictReader(f) if r.get("name")]
    if not rows:
        sys.exit(f"No places found in {CSV_IN}")

    # The text fed to the model: the name gives the model context the
    # description alone may lack ("Abbey Falls" says waterfall twice over).
    texts = [f"{r['name'].strip()}. {r['short_description'].strip()}" for r in rows]

    if encode is None:
        try:
            from sentence_transformers import SentenceTransformer
        except ImportError:
            sys.exit("sentence-transformers is not installed.\n"
                     "Run:  pip install sentence-transformers")
        model = SentenceTransformer(MODEL)
        encode = lambda t: model.encode(t, normalize_embeddings=True, show_progress_bar=True)

    vectors = encode(texts)

    out = [
        "-- =====================================================================",
        "--  Sanchari · 06e_seed_embeddings.sql",
        "--  Purpose    : One 384-number meaning-vector per place, for semantic",
        "--               search with pgvector (place_embedding).",
        "--  Author     : Swara",
        "--  Runs after : 06b_seed_places.sql",
        "--",
        "--  GENERATED by db/tools/make_embeddings.py from db/data/places.csv.",
        "--  Do not edit by hand - change the CSV and re-run the script.",
        f"--  Model: {MODEL} · {len(rows)} places",
        "-- =====================================================================",
        "",
    ]
    for r, vec in zip(rows, vectors):
        if len(vec) != 384:
            sys.exit(f"Expected 384 numbers for {r['name']}, got {len(vec)}")
        literal = "[" + ",".join(f"{float(x):.6f}" for x in vec) + "]"
        out.append(
            "INSERT INTO place_embedding (place_id, embedding, model_name)\n"
            f"SELECT p.place_id, {sql_text(literal)}::vector, {sql_text(MODEL)}\n"
            "FROM   place p JOIN destination d USING (destination_id)\n"
            f"WHERE  d.name = {sql_text(r['destination'].strip())}"
            f" AND d.state = {sql_text(r['state'].strip())}"
            f" AND p.name = {sql_text(r['name'].strip())};\n"
        )
    out += [
        "-- =====================================================================",
        "--  Sanity check - a semantic search. The query is embedded the same way;",
        "--  here we reuse Abbey Falls' own vector to find the places most like it:",
        "--",
        "--      SELECT p.name, ROUND((e.embedding <=> q.embedding)::numeric, 3) AS distance",
        "--      FROM   place_embedding e JOIN place p USING (place_id),",
        "--             (SELECT embedding FROM place_embedding",
        "--               WHERE place_id = (SELECT place_id FROM place WHERE name = 'Abbey Falls')) q",
        "--      ORDER  BY e.embedding <=> q.embedding",
        "--      LIMIT  5;",
        "-- =====================================================================",
    ]
    SQL_OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {SQL_OUT.relative_to(ROOT)} - {len(rows)} places")


if __name__ == "__main__":
    main()
